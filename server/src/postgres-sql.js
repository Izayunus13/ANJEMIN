// Translate the SQLite syntax used by the existing ANJEMIN queries.
export function splitStatements(sql) {
 const result=[];let start=0,quote=null,dollar=null;
 for(let i=0;i<sql.length;i++){
  if(dollar){if(sql.startsWith(dollar,i)){i+=dollar.length-1;dollar=null;}continue;}
  if(quote){if(sql[i]===quote){if(sql[i+1]===quote)i++;else quote=null;}continue;}
  if(sql[i]==="'"||sql[i]==='"'){quote=sql[i];continue;}
  if(sql[i]==='$'){const tag=sql.slice(i).match(/^\$[a-zA-Z_]*\$/)?.[0];if(tag){dollar=tag;i+=tag.length-1;continue;}}
  if(sql[i]===';'){const part=sql.slice(start,i).trim();if(part)result.push(part);start=i+1;}
 }
 const rest=sql.slice(start).trim();if(rest)result.push(rest);
 return result;
}
export function placeholders(sql){
 let quote=null,index=0,result='';
 for(let i=0;i<sql.length;i++){
  const c=sql[i];
  if(quote){result+=c;if(c===quote){if(sql[i+1]===quote)result+=sql[++i];else quote=null;}continue;}
  if(c==="'"||c==='"'){quote=c;result+=c;continue;}
  result+=c==='?'?'$'+(++index):c;
 }
 return result;
}
export function postgresSql(source,{returning=false}={}){
 let sql=source.trim();
 sql=sql.replace(/CREATE TRIGGER IF NOT EXISTS assign_user_number AFTER INSERT ON users\s+BEGIN INSERT INTO user_numbers\(user_id\) VALUES\(NEW.id\); END;?/gi,
 ()=>`CREATE OR REPLACE FUNCTION assign_user_number_fn() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN INSERT INTO user_numbers(user_id) VALUES(NEW.id); RETURN NEW; END $$;
 DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='assign_user_number' AND tgrelid='users'::regclass) THEN CREATE TRIGGER assign_user_number AFTER INSERT ON users FOR EACH ROW EXECUTE FUNCTION assign_user_number_fn(); END IF; END $$;`);
 sql=sql.replace(/\b(username|email)\s*=\s*\?\s+COLLATE NOCASE/gi,(_,column)=>'lower('+column+')=lower(?)');
 sql=sql.replace(/\s+COLLATE NOCASE\b/gi,'');
 sql=sql.replace(/INTEGER PRIMARY KEY AUTOINCREMENT/gi,'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
 sql=sql.replace(/CURRENT_TIMESTAMP/g,"to_char(timezone('UTC',CURRENT_TIMESTAMP),'YYYY-MM-DD HH24:MI:SS')");
 sql=sql.replace(/datetime\('now'\)/gi,'CURRENT_TIMESTAMP').replace(/datetime\(([\w.]+)\)/gi,'CAST($1 AS timestamptz)');
 sql=sql.replace(/printf\('([^']*)%0(\d+)d',([\w.]+)\)/gi,(_,prefix,width,column)=>"('"+prefix+"' || lpad("+column+"::text,GREATEST("+width+",length("+column+"::text)),'0'))");
 sql=sql.replace(/lower\(hex\(randomblob\(16\)\)\)/gi,"md5(random()::text || clock_timestamp()::text)");
 return splitStatements(sql).map(statement=>{
  const ignored=/^INSERT OR IGNORE\b/i.test(statement);
  if(ignored)statement=statement.replace(/^INSERT OR IGNORE\b/i,'INSERT');
  statement=placeholders(statement);
  if(ignored)statement+=' ON CONFLICT DO NOTHING';
  if(returning&&!/\bRETURNING\b/i.test(statement)){
   if(/^INSERT INTO order_messages\b/i.test(statement))statement+=' RETURNING id';
   if(/^INSERT INTO user_numbers\b/i.test(statement))statement+=' RETURNING number';
  }
  return statement;
 });
}
